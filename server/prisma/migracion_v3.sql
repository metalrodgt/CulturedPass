BEGIN;

-- ---------------------------------------------------------------------
-- 1) DNI en organizador
-- ---------------------------------------------------------------------
ALTER TABLE organizador ADD COLUMN IF NOT EXISTS dni TEXT;

-- 1.a) DNI de los administradores ya creados.
--      OPCIÓN A (recomendada): poné el DNI REAL de cada administrador.
--      Descomentá y editá una línea por cada administrador (el correo debe ser el suyo):
--
UPDATE organizador SET dni = '48416720' WHERE gmail = '414rodrigt14@gmail.com';
--
--      OPCIÓN B (automática): a los administradores que sigan sin DNI se les asigna uno
--      PROVISORIO de 8 dígitos (empieza con 9 + su id). Después podés cambiarlo desde la página.
UPDATE organizador
   SET dni = '9' || lpad(id_organizador::text, 7, '0')
 WHERE administrador = true AND dni IS NULL;

-- 1.b) Cualquier otra cuenta de organizador que exista también necesita DNI (la columna será obligatoria).
--      Se les asigna el mismo tipo de DNI provisorio.
UPDATE organizador
   SET dni = '9' || lpad(id_organizador::text, 7, '0')
 WHERE dni IS NULL;

-- 1.c) Ahora sí: obligatorio, único y con formato válido (7 u 8 números)
ALTER TABLE organizador ALTER COLUMN dni SET NOT NULL;
ALTER TABLE organizador ADD CONSTRAINT uq_organizador_dni UNIQUE (dni);
ALTER TABLE organizador ADD CONSTRAINT ck_organizador_dni CHECK (dni ~ '^[0-9]{7,8}$');

-- ---------------------------------------------------------------------
-- 2) Tabla de visitantes
-- ---------------------------------------------------------------------
CREATE TABLE visitante (
  id_visitante INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre       TEXT    NOT NULL,
  gmail        TEXT    NOT NULL,
  dni          TEXT    NOT NULL,
  numero_tel   TEXT    NOT NULL,
  contrasena   TEXT    NOT NULL,                       -- hash bcrypt, nunca texto plano
  aprobacion   BOOLEAN NOT NULL DEFAULT FALSE,         -- un organizador debe autorizarla
  CONSTRAINT uq_visitante_gmail     UNIQUE (gmail),
  CONSTRAINT uq_visitante_dni       UNIQUE (dni),
  CONSTRAINT ck_visitante_nombre    CHECK (length(btrim(nombre)) > 0),
  CONSTRAINT ck_visitante_gmail_min CHECK (gmail = lower(gmail)),
  CONSTRAINT ck_visitante_gmail_fmt CHECK (gmail ~ '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$'),
  CONSTRAINT ck_visitante_dni       CHECK (dni ~ '^[0-9]{7,8}$'),
  CONSTRAINT ck_visitante_tel       CHECK (numero_tel ~ '^[0-9+() -]{6,20}$')
);

-- ---------------------------------------------------------------------
-- 3) Boleto: se guardan el DNI y el teléfono de quien se inscribe
--    (los boletos viejos quedan con esos campos vacíos)
-- ---------------------------------------------------------------------
ALTER TABLE boleto ADD COLUMN IF NOT EXISTS dni        TEXT;
ALTER TABLE boleto ADD COLUMN IF NOT EXISTS numero_tel TEXT;
ALTER TABLE boleto ADD CONSTRAINT ck_boleto_dni CHECK (dni IS NULL OR dni ~ '^[0-9]{7,8}$');
ALTER TABLE boleto ADD CONSTRAINT ck_boleto_tel CHECK (numero_tel IS NULL OR numero_tel ~ '^[0-9+() -]{6,20}$');
-- Una persona (mismo DNI) no puede inscribirse dos veces al mismo evento
CREATE UNIQUE INDEX uq_boleto_evento_dni ON boleto (id_evento, dni) WHERE dni IS NOT NULL;

-- ---------------------------------------------------------------------
-- 4) Claves de registro (editables desde la página por el administrador)
-- ---------------------------------------------------------------------
CREATE TABLE configuracion (
  nombre TEXT PRIMARY KEY,
  valor  TEXT NOT NULL,
  CONSTRAINT ck_configuracion_valor CHECK (length(btrim(valor)) > 0)
);

INSERT INTO configuracion (nombre, valor) VALUES
  ('clave_organizador', 'CulturedPass7774'),
  ('clave_visitante',   'visitantes123')
ON CONFLICT (nombre) DO NOTHING;

-- ---------------------------------------------------------------------
-- 5) Seguridad: solo el backend accede (igual que las demás tablas)
-- ---------------------------------------------------------------------
ALTER TABLE visitante     ENABLE ROW LEVEL SECURITY;
ALTER TABLE configuracion ENABLE ROW LEVEL SECURITY;

COMMIT;

